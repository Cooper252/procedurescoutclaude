def main() -> int:
    existing = {r["slug"] for r in csv.DictReader(CAT.open(encoding="utf-8"))}
    header = next(csv.reader(CAT.open(encoding="utf-8")))
    want = [
        "slug",
        "name",
        "category",
        "unit",
        "codes",
        "source",
        "reviewed_by",
        "reviewed_at",
        "notes",
        "includes",
        "provider_types",
    ]
    rows = list(csv.DictReader(CAT.open(encoding="utf-8")))
    if header != want:  # add the two new columns to the file once
        for r in rows:
            r.setdefault("includes", "")
            r.setdefault("provider_types", "")
    added = 0
    for slug, name, cat, unit, codes, includes, types, _ in ROWS:
        if slug in existing:
            continue
        rows.append(
            {
                "slug": slug,
                "name": name,
                "category": cat,
                "unit": unit,
                "codes": codes,
                "source": "ai_suggested",
                "reviewed_by": "",
                "reviewed_at": "",
                "notes": "proposed for the standard list (D-042)",
                "includes": includes,
                "provider_types": "|".join(types),
            }
        )
        added += 1
    with CAT.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=want)
        w.writeheader()
        w.writerows(rows)
    syn_rows = list(csv.DictReader(SYN.open(encoding="utf-8")))
    have = {(r["slug"], r["term"].lower()) for r in syn_rows}
    syn_added = 0
    # words that fit several entries (e.g. "massage", "root canal") are left out:
    # the names already match them, and pointing them at one entry would steer people
    generic = {
        "massage",
        "root canal",
        "therapy",
        "implant",
        "wisdom teeth",
        "deep tissue",
        "swedish massage",
        "laser hair removal",
        "x-ray",
        "peel",
        "deep cleaning",
    }
    for slug, *_rest, synonyms in ROWS:
        for term in synonyms:
            if term.lower() in generic:
                continue
            if (slug, term.lower()) not in have:
                syn_rows.append(
                    {
                        "slug": slug,
                        "term": term,
                        "source": "ai_suggested",
                        "reviewed_by": "",
                        "reviewed_at": "",
                    }
                )
                have.add((slug, term.lower()))
                syn_added += 1
    with SYN.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["slug", "term", "source", "reviewed_by", "reviewed_at"])
        w.writeheader()
        w.writerows(syn_rows)
    print(f"services added: {added}, synonyms added: {syn_added}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
